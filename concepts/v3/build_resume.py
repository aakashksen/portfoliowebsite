"""Turn the resume LaTeX into resume.js (rendered on the site) and resume.md (the Markdown download),
and copy the compiled PDF next to them. Run after editing the resume:

    python build_resume.py [path/to/Aakash_Senthilnathan_Resume.tex]

The phone number is left out of the site and the Markdown on purpose; the PDF keeps it.
"""
import json, re, shutil, sys
from pathlib import Path

HERE = Path(__file__).parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / 'Work/resume/newdraft/Aakash_Senthilnathan_Resume.tex'


def clean(s):
    s = re.sub(r'\\(?:hspace|vspace)\*?\{[^}]*\}', '', s)
    s = re.sub(r'\\mbox\{([^}]*)\}', r'\1', s)
    s = s.replace(r'\textbar{}', '|').replace(r'\&', '&').replace(r'\$', '$').replace(r'\%', '%')
    s = s.replace('\\\\', '').replace('~', ' ')
    s = re.sub(r'\\daterange\{([^}]*)\}', r'\1', s)
    s = s.replace(r'\hfill', '\t')
    return re.sub(r'[ ]{2,}', ' ', s).strip()


def items(block):
    m = re.search(r'\\begin\{itemize\}(.*?)\\end\{itemize\}', block, re.S)
    return [clean(x) for x in re.split(r'\\item\s+', m.group(1))[1:]] if m else []


tex = SRC.read_text(encoding='utf-8')
tex = '\n'.join(l for l in tex.splitlines() if not l.lstrip().startswith('%'))  # drop comment lines
body = tex.split(r'\begin{document}', 1)[1]
name = re.search(r'\\LARGE\s*\\textbf\{([^}]*)\}', body).group(1)
sections = re.split(r'\\section\*\{([^}]*)\}', body)[1:]
out = {'name': name, 'source': SRC.name, 'sections': []}

for title, block in zip(sections[::2], sections[1::2]):
    block = block.split(r'\end{document}')[0]
    sec = {'title': title, 'entries': []}
    if title == 'Education':
        lines = [clean(l) for l in block.strip().splitlines() if clean(l)]
        head = re.match(r'\\textbf\{([^}]*)\}\s*\t?(.*)', lines[0])
        rest = []
        for l in lines[1:]:
            b = re.match(r'\\textbf\{([^}]*)\}\s*(.*)', l)
            rest.append({'label': b.group(1).rstrip(':'), 'text': b.group(2)} if b else {'text': l})
        sec['entries'].append({'title': head.group(1), 'dates': head.group(2).strip(), 'lines': rest})
    elif title == 'Experience':
        for m in re.finditer(r'\\experienceheading\{([^}]*)\}\{([^}]*)\}\{([^}]*)\}(.*?)(?=\\experienceheading|\Z)', block, re.S):
            sec['entries'].append({'title': clean(m.group(1)), 'org': clean(m.group(2)), 'dates': clean(m.group(3)), 'bullets': items(m.group(4))})
    elif title == 'Projects':
        for m in re.finditer(r'\\projectheading\{([^}]*)\}\{([^}]*)\}(.*?)(?=\\projectheading|\Z)', block, re.S):
            t = clean(m.group(1))
            name_, _, sub = t.partition(' - ')
            sec['entries'].append({'title': name_, 'org': sub, 'dates': clean(m.group(2)), 'bullets': items(m.group(3))})
    else:
        for m in re.finditer(r'\\textbf\{([^}]*)\}\s*(.*?)(?:\\\\|$)', block, re.M):
            sec['entries'].append({'label': clean(m.group(1)).rstrip(':'), 'text': clean(m.group(2))})
    out['sections'].append(sec)

# Markdown
md = [f'# {name}', '', 'aakash.senthilnathan@gmail.com · [LinkedIn](https://linkedin.com/in/aakashsenthilnathan) · [GitHub](https://github.com/aakashksen)', '']
for sec in out['sections']:
    md += [f'## {sec["title"]}', '']
    for e in sec['entries']:
        if 'bullets' in e:
            md += [f'### {e["title"]}' + (f' — {e["org"]}' if e.get('org') else ''), f'*{e["dates"]}*', '']
            md += [f'- {b}' for b in e['bullets']] + ['']
        elif 'lines' in e:
            md += [f'### {e["title"]}', f'*{e["dates"]}*', '']
            for l in e['lines']:
                md += [(f'**{l["label"]}:** ' if l.get('label') else '') + l['text'], '']
        else:
            md.append(f'- **{e["label"]}:** {e["text"]}')
    md.append('')

(HERE / 'resume.md').write_text('\n'.join(md).strip() + '\n', encoding='utf-8')
(HERE / 'resume.js').write_text('// Generated by build_resume.py from ' + SRC.name + '. Do not edit by hand.\nwindow.RESUME = '
                                + json.dumps(out, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
pdf = SRC.with_suffix('.pdf')
if pdf.exists():
    shutil.copyfile(pdf, HERE / 'resume.pdf')
print('sections:', [(s['title'], len(s['entries'])) for s in out['sections']], '| pdf copied:', pdf.exists())
